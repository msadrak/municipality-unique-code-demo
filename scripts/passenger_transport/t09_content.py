def F(fid, label, guide, vtype, need, fm=(), el=(), lp=(), opts=None, why=None, locked=False, cond=None):
    """یک فیلد فرم.

    lp: نام گروه‌های LPG یا شناسهٔ مستقیم LP.
    opts: متن گزینه‌ها در خانهٔ مقدار.
    locked: کاربر پر نمی‌کند (فقط پس از تصمیم مرجع یا خودکار).
    cond: متن شرط (برای need=cond).
    """
    return dict(kind="field", fid=fid, label=label, guide=guide, vtype=vtype, need=need,
                fm=list(fm), el=list(el), lp=list(lp), opts=opts, why=why, locked=locked, cond=cond)


def T(fid, label, guide, vtype, need, cols, rows, empty_rows=0, fm=(), el=(), lp=(), why=None,
      cond=None, note=None, widths=None, fixed=None):
    """یک جدول تکرارشونده (مثل کسور یا اقلام).

    fixed: {شمارهٔ ستون: متن} برای خانه‌هایی که کاربر پر نمی‌کند (خاکستری).
    """
    return dict(kind="table", fid=fid, label=label, guide=guide, vtype=vtype, need=need, cols=cols,
                rows=rows, empty_rows=empty_rows, fm=list(fm), el=list(el), lp=list(lp), why=why,
                cond=cond, note=note, widths=widths, fixed=fixed or {})


def C(fid, label, items, fm=(), el=(), lp=(), why=None):
    """فهرست بررسی پیوست‌ها: items = [(عنوان، شرط)]."""
    return dict(kind="check", fid=fid, label=label, items=items, fm=list(fm), el=list(el), lp=list(lp),
                why=why, vtype="up", need="cond")


def S(fid, label, roles, fm=(), el=(), lp=(), why=None, note=None):
    """جدول تأیید کارکنان."""
    return dict(kind="sign", fid=fid, label=label, roles=roles, fm=list(fm), el=list(el), lp=list(lp),
                why=why, vtype="sign", need="sign", note=note)


def SEC(title, items, cond=None, note=None, landscape=False):
    return dict(title=title, items=items, cond=cond, note=note)


