def bn(x: int) -> str:
    """میلیارد واحد منبع با یک رقم اعشار، ارقام فارسی."""
    return f"{x / 1e9:,.1f}".translate(FA).replace(".", "٫")


def mn(x: int) -> str:
    """میلیون واحد منبع با یک رقم اعشار (صفر اعشاری حذف)، ارقام فارسی."""
    s = f"{x / 1e6:,.1f}"
    return (s[:-2] if s.endswith(".0") else s).translate(FA).replace(".", "٫")


def fa(x) -> str:
    return (f"{x:,}" if isinstance(x, int) else str(x)).translate(FA)


