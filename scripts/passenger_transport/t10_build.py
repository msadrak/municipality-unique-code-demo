NAVY = "1F3864"
THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def fit_height(ws, row, ncols, base=12.5):
    """ارتفاع سطر بر پایهٔ طول متن و پهنای ستون؛ openpyxl ارتفاع را خودکار تنظیم نمی‌کند."""
    lines = 1
    for j in range(1, ncols + 1):
        v = ws.cell(row=row, column=j).value
        if v is None:
            continue
        w = ws.column_dimensions[get_column_letter(j)].width or 10
        per = max(int(w * 1.15), 6)
        n = sum(max(1, -(-len(part) // per)) for part in str(v).split("\n"))
        lines = max(lines, n)
    ws.row_dimensions[row].height = min(409, lines * base + 4)


def sheet(wb, title, heading, note, cols, rows, widths, first=False):
    ws = wb.active if first else wb.create_sheet()
    ws.title = title
    ws.sheet_view.rightToLeft = True
    ws["A1"] = heading
    ws["A1"].font = Font(name="Tahoma", size=13, bold=True, color=NAVY)
    ws["A2"] = note
    ws["A2"].font = Font(name="Tahoma", size=9, color="7F0000")
    ws["A2"].alignment = Alignment(wrap_text=True, vertical="top")
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=len(cols))
    ws.row_dimensions[2].height = 42
    for j, c in enumerate(cols, 1):
        cell = ws.cell(row=3, column=j, value=c)
        cell.font = Font(name="Tahoma", size=9, bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor=NAVY)
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        cell.border = BORDER
        ws.column_dimensions[get_column_letter(j)].width = widths[j - 1] if j - 1 < len(widths) else 18
    for i, r in enumerate(rows, 4):
        for j, v in enumerate(r, 1):
            cell = ws.cell(row=i, column=j, value=v)
            cell.font = Font(name="Tahoma", size=9, bold=(j == 1))
            cell.alignment = Alignment(wrap_text=True, vertical="top")
            cell.border = BORDER
            if j == 1:
                cell.fill = PatternFill("solid", fgColor="EEF2F8")
        fit_height(ws, i, len(cols))
    ws.row_dimensions[3].height = 30
    ws.freeze_panes = "C4"
    ws.auto_filter.ref = f"A3:{get_column_letter(len(cols))}{3 + len(rows)}"
    return ws


def block(ws, start_row, title, note, cols, rows, num_cols=()):
    ws.cell(row=start_row, column=1, value=title).font = Font(name="Tahoma", size=11, bold=True, color=NAVY)
    if note:
        c = ws.cell(row=start_row + 1, column=1, value=note)
        c.font = Font(name="Tahoma", size=8.5, color="595959")
        c.alignment = Alignment(wrap_text=True, vertical="top")
        ws.merge_cells(start_row=start_row + 1, start_column=1, end_row=start_row + 1, end_column=max(len(cols), 6))
        ws.row_dimensions[start_row + 1].height = 48
    h = start_row + 2
    for j, c in enumerate(cols, 1):
        cell = ws.cell(row=h, column=j, value=c)
        cell.font = Font(name="Tahoma", size=9, bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor="44546A")
        cell.alignment = Alignment(wrap_text=True, horizontal="center", vertical="center")
        cell.border = BORDER
    for i, r in enumerate(rows, h + 1):
        for j, v in enumerate(r, 1):
            cell = ws.cell(row=i, column=j, value=v)
            cell.font = Font(name="Tahoma", size=9)
            cell.border = BORDER
            cell.alignment = Alignment(wrap_text=True, vertical="top")
            if (j - 1) in num_cols and isinstance(v, (int, float)):
                cell.number_format = "#,##0"
        fit_height(ws, i, len(cols))
    ws.row_dimensions[h].height = 30
    return h + 1 + len(rows) + 1


