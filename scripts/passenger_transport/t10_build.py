def k05_evidence(q):
    rows = q("""select s.vahed, s.person, c.kind, sum(s.bed), sum(s.bes) from sanad s join doc_class c on c.doc_key=s.doc_key
        where s.org='Terminals' and s.fy='1404' and s.hcode='113-1-4-0' and c.kind in ('OPENING','REGULAR') group by 1,2,3""")
    clo = q("""select sum(s.bes), sum(s.bed) from sanad s join doc_class c on c.doc_key=s.doc_key
        where s.org='Terminals' and s.fy='1404' and s.hcode='113-1-4-0' and c.kind='CLOSING_PERMANENT'""")[0]
    billed = set(q(f"select distinct s.vahed, s.person {K04_BASE}"))
    P = defaultdict(lambda: [0, 0])  # [ماندهٔ افتتاحیه، گردش اسناد عادی]
    for v, p, k, bd, bs in rows:
        P[(v or "", p)][0 if k == "OPENING" else 1] += int(bd) - int(bs)
    bal = {k: a + b for k, (a, b) in P.items()}
    dr = [k for k, b in bal.items() if b > 0]
    cr = [k for k, b in bal.items() if b < 0]
    code = defaultdict(int)
    for (v, _), b in bal.items():
        code[v] += b
    k5 = dict(dr_n=len(dr), dr=sum(bal[k] for k in dr), cr_n=len(cr), cr=-sum(bal[k] for k in cr),
              dr_codes=len({v for v, _ in dr}), cr_codes=len({v for v, _ in cr}), both=len({v for v, _ in dr} & {v for v, _ in cr}),
              cr_blank=sum(1 for v, _ in cr if not v), op_dr=sum(a for a, _ in P.values() if a > 0), op_cr=-sum(a for a, _ in P.values() if a < 0),
              cr_open=sum(1 for k in cr if P[k][0] < 0), cr_unbilled=sum(1 for k in cr if k not in billed),
              cr_unbilled_amt=-sum(bal[k] for k in cr if k not in billed), dr_unbilled=sum(1 for k in dr if k not in billed),
              dr_unbilled_amt=sum(bal[k] for k in dr if k not in billed),
              code_dr_n=sum(1 for b in code.values() if b > 0), code_dr=sum(b for b in code.values() if b > 0),
              code_cr_n=sum(1 for b in code.values() if b < 0), code_cr=-sum(b for b in code.values() if b < 0),
              closing_cr=int(clo[0]), closing_dr=int(clo[1]))
    k5["net"] = k5["dr"] - k5["cr"]
    k5["match"] = k5["closing_cr"] == k5["dr"] and k5["closing_dr"] == k5["cr"]
    return k5


