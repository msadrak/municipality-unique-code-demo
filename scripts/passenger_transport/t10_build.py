def evidence(con):
    q = lambda s, *a: con.execute(s, a).fetchall()  # noqa: E731
    E = {"k04": k04_evidence(q), "k05": k05_evidence(q), "x": excl_evidence(q)}
    # K-01: ثبت دفتری خدمات پیمانکاری و انرژی به تفکیک کد واحد
    acc = {"113-1-1-22": "out", "113-1-1-23": "out", "113-1-1-29": "util", "113-1-1-31": "util", "113-1-1-32": "util"}
    r = q(f"""select substr(s.vahed,1,3), s.hcode, sum(s.bed)-sum(s.bes) from sanad s join doc_class c on c.doc_key=s.doc_key
        where s.org='Terminals' and s.fy='1404' and c.kind='REGULAR' and s.hcode in ({','.join('?' * len(acc))}) group by 1,2""", *acc)
    k01 = defaultdict(lambda: dict(out=0, util=0))
    by_acc = defaultdict(dict)
    for t, h, amt in r:
        k01[t][acc[h]] += int(amt)
        by_acc[h][t] = int(amt)
    E["k01"] = [dict(t=t, name=TERMINAL.get(t, t), **v) for t, v in sorted(k01.items())]
    docs = q("""select s.doc_key, count(distinct substr(s.vahed,1,3)) from sanad s join doc_class c on c.doc_key=s.doc_key
        where s.org='Terminals' and s.fy='1404' and c.kind='REGULAR' and s.hcode in ('113-1-1-22','113-1-1-23') and cast(s.bed as real)>0 group by 1""")
    E["k01_docs"] = (len(docs), sum(1 for _, n in docs if n > 1))
    eq = []
    for h in ("113-1-1-22", "113-1-1-23"):
        ts = sorted(t for t in by_acc[h] if t in ("001", "002", "003", "004", "007"))
        for i, a in enumerate(ts):
            for b in ts[i + 1:]:
                if abs(by_acc[h][a] - by_acc[h][b]) <= 2:
                    eq.append((h, a, b, by_acc[h][a], by_acc[h][b]))
    E["k01_equal"] = eq
    # تاکسیرانی: کد فعالیت منبع
    tx = q("""select s.markaz, max(s.f1), sum(case when s.hcode like '611-%' then s.bed-s.bes else 0 end),
        sum(case when s.hcode not like '611-%' then s.bed-s.bes else 0 end), count(*)
        from sanad s join doc_class c on c.doc_key=s.doc_key
        where s.org='Taxi' and s.fy='1404' and c.kind='REGULAR' and (s.hcode like '611-%' or s.hcode like '612-%' or s.hcode like '613-%') group by 1""")
    E["tx_total"] = (sum(int(x[2]) for x in tx), sum(int(x[3]) for x in tx))
    E["tx"] = {x[0]: dict(title=x[1], pay=int(x[2]), non=int(x[3]), n=x[4]) for x in tx}
    return E


