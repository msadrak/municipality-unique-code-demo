    eqre = re.compile(r"تقریباً برابرند|تقسیم مساوی (?:شده|انجام شده)|به‌طور مساوی تقسیم شده")
    add("C-20", "از مبالغ نزدیک به هم سازوکار تقسیم مساوی نتیجه گرفته نشده است", not eqre.search(text + md), eqre.search(text + md).group(0) if eqre.search(text + md) else "۰")
    return res


