def controls(E, built, md):
    tp, kp, xr = built["tp"], built["kp"], built["xr"]
    res = []

    def add(cid, title, ok, detail):
        res.append(dict(id=cid, title=title, status="PASS" if ok else "FAIL", detail=detail))

    from openpyxl import load_workbook
    wb = load_workbook(OUT_XLSX, read_only=True)
    add("C-01", "کتاب‌کار حداکثر ۵ شیت دارد", len(wb.sheetnames) <= 5, f"{len(wb.sheetnames)}: {', '.join(wb.sheetnames)}")
    add("C-02", "۳ تا ۵ موضوع بهایابی", 3 <= len(CO) <= 5, str(len(CO)))
    add("C-03", "حداکثر ۸ شاخص", len(kp) <= 8, str(len(kp)))
    co_ids = {c[0] for c in CO}
    tp_cos = {x.strip() for r in tp for x in re.split("[،,]", r[1]) if x.strip().startswith("CO-")} | ({c for c in co_ids} if any(r[1] == "همهٔ موضوع‌ها" for r in tp) else set())
    kp_cos = {m for r in kp for m in re.findall(r"CO-\d\d", r[10])}
    add("C-04", "هر موضوع دست‌کم یک مسیر ردیابی و یک شاخص دارد", co_ids <= tp_cos and co_ids <= kp_cos,
        f"بی‌مسیر: {sorted(co_ids - tp_cos)}؛ بی‌شاخص: {sorted(co_ids - kp_cos)}")
    fids = {it["fid"] for f in T9.FORMS for s in f["sections"] for it in s["items"]}
